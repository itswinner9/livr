export function demoRating(propertyId: string): RatingSummary {
  return calculateRatingSummary(
    allDemoReviews.filter((r) => r.property_id === propertyId && r.status === "published"),
  );
}

export function demoRentHistory(propertyId: string): RentHistoryGroup[] {
  const extra = demoRentReports.filter((r) => r.property_id === propertyId);
  const fromReviews = allDemoReviews
    .filter((r) => r.property_id === propertyId && r.monthly_rent && r.bedrooms != null)
    .map((r) => ({
      bedrooms: r.bedrooms!,
      monthly_rent: r.monthly_rent!,
      lease_start_year: r.move_in_year,
    }));
  return aggregateRentHistory(
    [...extra, ...fromReviews].map((r) => ({
      bedrooms: r.bedrooms,
      monthly_rent: r.monthly_rent,
      lease_start_year: r.lease_start_year ?? null,
    })),
  );
}
